# ① 输入年龄
def age_fn(prompt):
    while True:
        try:
            value = int(input(prompt))
            if value > 0:
                return value
            else:
                print('❌ 请输入正整数!')
                continue

        except ValueError:
            print('❌ 请输入数字!')
            continue


res = age_fn('请输入您的年龄:')
print(res)

