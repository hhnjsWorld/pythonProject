"""
Python 异常处理（try / except / else / finally）语法速查表
"""

# ============================================================
# 一、语法格式表
# ============================================================
table = """
┌──────────────────────┬──────────────────────────────────────────────────┐
│ 关键字               │ 作用说明                                         │
├──────────────────────┼──────────────────────────────────────────────────┤
│ try:                 │ 放置可能出问题的代码                             │
├──────────────────────┼──────────────────────────────────────────────────┤
│ except Exception as e│ 出问题后的解决方案（捕获异常并处理）             │
├──────────────────────┼──────────────────────────────────────────────────┤
│ else:                │ 如果没有出问题（即没有执行 except），则执行这里  │
├──────────────────────┼──────────────────────────────────────────────────┤
│ finally:             │ 无论是否出问题，都会执行；一般用于释放资源       │
└──────────────────────┴──────────────────────────────────────────────────┘
"""

# ============================================================
# 二、执行流程表
# ============================================================
flow = """
                    ┌─────────────┐
                    │     try     │
                    └──────┬──────┘
                           │
              ┌────────────┴────────────┐
              │                         │
        出问题? 是                  出问题? 否
              │                         │
              ▼                         ▼
        ┌───────────┐           ┌───────────┐
        │  except   │           │   else    │
        └─────┬─────┘           └─────┬─────┘
              │                         │
              └────────────┬────────────┘
                           ▼
                    ┌─────────────┐
                    │   finally   │  ( 无论是否出问题都会执行)
                    └─────────────┘
"""

# ============================================================
# 三、标准代码模板
# ============================================================
template = """
try:
    # 可能出问题的代码
    pass

except Exception as e:
    # 出问题后的解决方案
    print("发生异常：", e)

else:
    # 没有出问题时执行（没有进入 except）
    pass

finally:
    # 无论是否出问题都会执行，一般用于释放资源
    pass
"""

if __name__ == "__main__":
    print(table)
