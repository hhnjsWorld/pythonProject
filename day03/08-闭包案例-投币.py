# ------------------------------------------------------------
# 一、场景引入
# ------------------------------------------------------------
# 想象小区门口的摇摇车：
#   - 你投 1 块钱，摇 3 分钟
#   - 你再投 1 块钱，累计 2 块，摇 6 分钟
#   - 机器要"记住"你一共投了多少钱
#
# 问题：这个"累计金额"存在哪里？
#   - 存在全局变量？→ 谁都能改，不安全（数据私有化问题）
#   - 存在函数局部变量？→ 函数执行完就销毁了，记不住（状态保持问题）
#
# 答案：用闭包！


# ------------------------------------------------------------
# 二、先用"错误写法"感受问题
# ------------------------------------------------------------

# 错误写法 1：用全局变量存余额
#   问题：全局变量在任何地方都能被修改，没有隐私保护
balance = 0  # 全局变量，谁都能改


def insert_coin_global(amount):
    global balance
    balance += amount
    print(f'投币 {amount} 元，当前余额：{balance} 元')


insert_coin_global(1)   # 投币 1 元，当前余额：1 元
insert_coin_global(2)   # 投币 2 元，当前余额：3 元

# 危险！外部可以直接篡改余额
balance = 99999  # 直接改成 9 万多，机器数据被污染了
print(f'被篡改后的余额：{balance} 元')
# 这就是全局变量的问题：没有数据私有化，谁都能碰

print('*' * 50)


# 错误写法 2：用局部变量存余额
#   问题：函数执行完毕，局部变量就被销毁了，记不住状态
def insert_coin_local(amount):
    balance = 0  # 每次调用都重新初始化为 0
    balance += amount
    print(f'投币 {amount} 元，当前余额：{balance} 元')


insert_coin_local(1)   # 投币 1 元，当前余额：1 元
insert_coin_local(2)   # 投币 2 元，当前余额：2 元（不是 3！因为每次都重置了）
# 局部变量的问题：函数结束就释放内存，状态保持不住

print('*' * 50)


# ------------------------------------------------------------
# 三、闭包解决方案（核心）
# ------------------------------------------------------------
# 闭包 = 内部函数 + 外部环境
# 外部函数的变量被内部函数引用，函数结束后不销毁 → 状态保持住了
# 外部变量是局部的，外面访问不到 → 数据私有化实现了

def coin_machine():
    """
    投币机工厂函数（外部函数）
    返回一个闭包（内部函数），每次调用闭包就是投一次币
    """
    # 外部函数变量：余额
    # 这是局部变量，外面访问不到 → 数据私有化
    balance = 0

    def insert_coin(amount=1):
        """
        投币函数（内部函数 = 闭包）
        :param amount: 投币金额，默认 1 元
        """
        # 要修改外部函数的变量 balance，必须用 nonlocal 声明
        # 不写 nonlocal 的话，Python 会认为你在定义一个新的局部变量
        nonlocal balance
        balance += amount
        print(f'🪙 投币 {amount} 元 → 当前余额：{balance} 元')
        return balance

    # 外部函数返回内部函数对象（不是调用！）
    return insert_coin


# ------------------------------------------------------------
# 四、使用闭包（正确的调用方式）
# ------------------------------------------------------------

# 第一步：调用外部函数，拿到闭包（内部函数对象）
# 这一步执行后，balance = 0 被创建，并且被 insert_coin 闭包"锁住"
# coin_machine() 执行完毕，但 balance 不会被回收，因为闭包还引用着它
machine = coin_machine()

# 第二步：多次调用闭包 → 操作同一个 balance → 状态累加
machine(1)   # 🪙 投币 1 元 → 当前余额：1 元
machine(2)   # 🪙 投币 2 元 → 当前余额：3 元
machine(5)   # 🪙 投币 5 元 → 当前余额：8 元

# 验证数据私有化：外部能直接改 balance 吗？
# print(balance)  # ❌ 报错！name 'balance' is not defined
# 外部根本访问不到 balance，它被闭包保护起来了

print('*' * 50)


# ------------------------------------------------------------
# 五、常见错误：outer()() vs res = outer(); res()
# ------------------------------------------------------------
# 这是初学者最容易踩的坑，必须搞清楚！

# 错误写法：每次都重新调用外部函数
# 每次 coin_machine() 都创建一个全新的 balance=0 和全新的闭包
# 三次调用是三台独立的机器，互不相干
coin_machine()(1)   # 机器A：投币 1 元 → 余额 1 元，然后机器A被丢弃
coin_machine()(2)   # 机器B：投币 2 元 → 余额 2 元，然后机器B被丢弃
coin_machine()(5)   # 机器C：投币 5 元 → 余额 5 元，然后机器C被丢弃
# 余额永远不会累加，因为每次都是新机器！

print('--- 对比分割线 ---')

# 正确写法：调用一次外部函数，保存闭包，反复使用
machine2 = coin_machine()   # 只创建一台机器，一个 balance
machine2(1)   # 同一台机器：余额 1
machine2(2)   # 同一台机器：余额 3
machine2(5)   # 同一台机器：余额 8

print('*' * 50)


# ------------------------------------------------------------
# 六、升级版：多功能投币机（投币 + 查询 + 消费 + 重置）
# ------------------------------------------------------------
# 一个闭包可以返回多个内部函数，用字典组织起来
# 这样就能对同一个 balance 做多种操作

def smart_coin_machine():
    """智能投币机：支持投币、查询余额、消费、重置"""
    balance = 0  # 被保护的余额

    def insert_coin(amount):
        """投币"""
        nonlocal balance
        if amount <= 0:
            print('❌ 投币金额必须大于 0')
            return
        balance += amount
        print(f'🪙 投币 {amount} 元 → 余额：{balance} 元')

    def check_balance():
        """查询余额（只读，不需要 nonlocal）"""
        print(f'💰 当前余额：{balance} 元')
        return balance

    def spend(amount):
        """消费（扣余额）"""
        nonlocal balance
        if amount > balance:
            print(f'❌ 余额不足！需要 {amount} 元，当前只有 {balance} 元')
            return
        balance -= amount
        print(f'🎮 消费 {amount} 元 → 剩余余额：{balance} 元')

    def reset():
        """重置机器（清零）"""
        nonlocal balance
        balance = 0
        print('🔄 机器已重置，余额归零')

    # 用字典返回多个内部函数，调用者可以通过 key 选择功能
    return {
        'insert': insert_coin,
        'check': check_balance,
        'spend': spend,
        'reset': reset
    }


# 使用智能投币机
print('=== 智能投币机演示 ===')
machine3 = smart_coin_machine()

machine3['check']()     # 💰 当前余额：0 元
machine3['insert'](10)  # 🪙 投币 10 元 → 余额：10 元
machine3['insert'](5)   # 🪙 投币 5 元 → 余额：15 元
machine3['spend'](8)    # 🎮 消费 8 元 → 剩余余额：7 元
machine3['spend'](10)   # ❌ 余额不足！需要 10 元，当前只有 7 元
machine3['check']()     # 💰 当前余额：7 元
machine3['reset']()     # 🔄 机器已重置，余额归零
machine3['check']()     # 💰 当前余额：0 元

print('*' * 50)


# ------------------------------------------------------------
# 七、内存机制揭秘（结合垃圾回收）
# ------------------------------------------------------------
# 为什么闭包能让局部变量不被回收？
#
# Python 的垃圾回收主要靠【引用计数】：
#   - 一个对象被引用的次数 → 引用计数
#   - 引用计数归 0 → 对象立即被销毁，内存释放
#
# 正常情况下，coin_machine() 执行完，balance 应该被回收。
# 但闭包 insert_coin 的 __closure__ 属性里，有一个 cell 对象引用着 balance。
# 引用链：machine 变量 → insert_coin 函数对象 → __closure__ → cell → balance
# 只要 machine 还活着，这条引用链就不断，balance 的引用计数就不为 0，就不会被回收。
#
# 这就是闭包实现"状态保持"和"数据私有化"的底层原理。

def demo_closure_memory():
    """演示闭包的 __closure__ 属性"""
    secret = '我是被闭包保护的数据'

    def inner():
        print(secret)

    return inner


fn = demo_closure_memory()

# 查看闭包的 __closure__ 属性
print(f'闭包的 __closure__：{fn.__closure__}')
# 输出类似：(<cell at 0x...: str object at 0x...>,)

# cell.cell_contents 就是被锁住的变量
print(f'cell 中保存的内容：{fn.__closure__[0].cell_contents}')
# 输出：我是被闭包保护的数据

print('*' * 50)


# ------------------------------------------------------------
# 八、手动释放闭包内存
# ------------------------------------------------------------
# 闭包锁住的变量不会自动释放，除非解除引用。
# 当闭包持有大对象（比如 1GB 的数据）时，要注意手动释放。

def big_data_closure():
    """模拟闭包持有大数据"""
    huge_data = list(range(1000000))  # 假设有一百万元素的大数据

    def get_length():
        return len(huge_data)

    return get_length


big_fn = big_data_closure()
print(f'大数据长度：{big_fn()}')

# 手动释放方式 1：del 掉持有闭包的变量
# del big_fn
# → big_fn 引用计数归零
# → 内部函数对象被回收
# → __closure__ 被销毁
# → cell 对象引用计数归零
# → huge_data 被回收

# 手动释放方式 2：把 cell 里的大对象替换为 None
# big_fn.__closure__[0].cell_contents = None
# → huge_data 没有被引用了，立即被回收
# → 闭包本身还在，但大数据已经释放了

print('*' * 50)


