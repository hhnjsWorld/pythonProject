"""
【闭包投币机案例 - 知识地图】

1. 闭包三要素（六字真言）：嵌套、引用、返回
   - 嵌套：外部函数里定义内部函数
   - 引用：内部函数使用外部函数的变量
   - 返回：外部函数返回内部函数对象

2. 闭包两大作用：
   - 状态保持：外部变量被闭包锁住，函数结束不销毁
   - 数据私有化：外部变量是局部的，外面访问不到

3. nonlocal 关键字：
   - 内部函数要修改外部变量时，必须用 nonlocal 声明
   - 只读访问不需要 nonlocal
   - 对比：global 修改全局变量，nonlocal 修改外层函数变量

4. 调用方式（重点易错）：
   - ❌ coin_machine()(1) 每次都是新机器，不累加
   - ✅ m = coin_machine(); m(1); m(2) 同一台机器，累加

5. 内存机制：
   - 闭包通过 __closure__ → cell → 变量 的引用链
   - 让外部局部变量逃过引用计数的回收
   - 手动释放：del 闭包变量 或 cell_contents = None

6. 多函数闭包：
   - 外部函数可以返回多个内部函数（用字典组织）
   - 所有内部函数共享同一个外部变量
   - 可以实现投币、查询、消费、重置等多种操作
"""
