# 先进后出  后进先出
# 举例 : 1.枪装子弹 -> 后装的先发射出,先装的后发射出来
#       2. 洗出来的盘子 -> 第一个放的盘子在最后洗,最新放的盘子第一个洗

# 应用题
# ①
def foo1(e):
    print(e, '1 ↓')
    foo2(e)
    print(e, '2 stop')
    return e  # 加上这行


def foo2(e):
    print(e, '3 ↓')


result = foo1('顺序')
print(result)


# ②
#        ← 栈顶
#     ┌─────────┐
#     │   f1    │  第4层（最顶层，正在执行）
#     ├─────────┤
#     │   f2    │  第3层
#     ├─────────┤
#     │   f3    │  第2层
#     ├─────────┤
#     │ 主程序   │  第1层（最底下）
#     └─────────┘
#         ← 栈底
# 为什么是 4 层？一步步推：
# 主程序开始 → 栈里 1 层（主程序）
# 主程序调用 f3 → f3 入栈，栈里 2 层（主程序 + f3）
# f3 里调用 f2 → f2 入栈，栈里 3 层（主程序 + f3 + f2）
# f2 里调用 f1 → f1 入栈，栈里 4 层（主程序 + f3 + f2 + f1）
# 到第 4 步的时候，栈达到最深，有 4 层。

def f1():
    print("f1")


def f2():
    print("f2")
    f1()


def f3():
    print("f3")
    f2()


f3()
